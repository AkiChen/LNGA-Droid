#!/usr/bin/env python3
"""Import LNGA HarmonyOS emotion assets into Android resources.

Usage: tools/import_harmony_emotions.py /path/to/lnga_harmony
"""

from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path


ENTRY_RE = re.compile(
    r"EM\.set\('([^']+)', \$rawfile\('emotions/([^']+\.png)'\)\)"
)


def resource_name(relative_path: str) -> str:
    stem = relative_path.removesuffix(".png").replace("/", "_")
    return "nga_emotion_" + re.sub(r"[^a-zA-Z0-9_]", "_", stem).lower()


def numeric_alias(category: str, relative_path: str) -> str | None:
    filename = Path(relative_path).stem
    prefixes = {
        "ac": "ac",
        "a2": "a2_",
        "ng": "ng_",
        "pst": "pt",
        "dt": "dt",
        "pg": "pg",
    }
    prefix = prefixes.get(category)
    if prefix is None or not filename.startswith(prefix):
        return None
    suffix = filename[len(prefix):]
    return str(int(suffix)) if suffix.isdigit() else None


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("Pass the LNGA HarmonyOS repository path")

    android_root = Path(__file__).resolve().parents[1]
    harmony_root = Path(sys.argv[1]).resolve()
    mapping_file = harmony_root / "entry/src/main/ets/common/media/EmotionResources.ets"
    source_root = harmony_root / "entry/src/main/resources/rawfile/emotions"
    drawable_root = android_root / "app/src/main/res/drawable-nodpi"
    kotlin_file = android_root / "app/src/main/java/com/aki/lnga/ui/NgaEmotionResources.kt"

    entries = ENTRY_RE.findall(mapping_file.read_text(encoding="utf-8"))
    if not entries:
        raise SystemExit(f"No emotion mappings found in {mapping_file}")

    drawable_root.mkdir(parents=True, exist_ok=True)
    aliases: dict[str, str] = {}
    for key, relative_path in entries:
        target_name = resource_name(relative_path)
        shutil.copy2(source_root / relative_path, drawable_root / f"{target_name}.png")
        aliases[key] = target_name
        category = key.split(":", 1)[0]
        number = numeric_alias(category, relative_path)
        if number is not None:
            aliases[f"{category}:{number}"] = target_name
            if category == "pst":
                aliases[f"pt:{number}"] = target_name

    lines = [
        "package com.aki.lnga.ui",
        "",
        "import androidx.annotation.DrawableRes",
        "import com.aki.lnga.R",
        "",
        "/** Generated by tools/import_harmony_emotions.py from the LNGA resources. */",
        "internal object NgaEmotionResources {",
        "    private val resources = mapOf(",
    ]
    for key, target_name in sorted(aliases.items()):
        escaped_key = key.replace('\\', '\\\\').replace('"', '\\"')
        lines.append(f'        "{escaped_key}" to R.drawable.{target_name},')
    lines += [
        "    )",
        "",
        "    @DrawableRes",
        "    fun resolve(category: String, code: String): Int? {",
        "        val normalizedCategory = if (category.lowercase() == \"pt\") \"pst\" else category.lowercase()",
        "        val normalizedCode = code.toIntOrNull()?.toString() ?: code",
        "        return resources[\"$normalizedCategory:$normalizedCode\"]",
        "    }",
        "",
        "    fun needsLightBackground(category: String): Boolean =",
        "        category.lowercase() in setOf(\"ac\", \"a2\", \"dt\")",
        "}",
        "",
    ]
    kotlin_file.write_text("\n".join(lines), encoding="utf-8")
    print(f"Imported {len(entries)} emotions and generated {len(aliases)} aliases")


if __name__ == "__main__":
    main()
